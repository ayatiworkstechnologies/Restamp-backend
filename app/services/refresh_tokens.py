"""RESTAMP Phase 6 — refresh-token lifecycle.

- Secure creation, validation, rotation, reuse prevention, replay detection
- Expiration enforcement, concurrency safety (savepoint-based, transactional)
- Refresh tokens are NEVER usable as access tokens.
- All operations are savepoint-based so concurrent requests on the same JTI
  race safely: only one wins; the other gets a clean "token already rotated/revoked"
  result and must retry or re-authenticate.
"""
from __future__ import annotations

import time

from fastapi import HTTPException, status
from sqlalchemy.exc import SQLAlchemyError
from sqlalchemy.orm import Session

from ..models import User, RefreshToken
from ..security import decode_token


TEST_JTI_PREFIX = "rt-"  # distinguish refresh-token JTIs from access-token JTIs


def create_refresh_token(
    db: Session,
    user_id: int,
    jti: str | None = None,
    ip_address: str | None = None,
    user_agent: str | None = None,
) -> RefreshToken:
    """Create a new refresh token for *user_id*.

    - If *jti* is omitted, one is generated from ``jti = f'{TEST_JTI_PREFIX}{user_id}:{int(time.time())}'``.
    - The token_hash is the SHA-256 of the raw random value; we store only the hash
      (never the plain token) for replay prevention.
    - On success the token is non-revoked, non-expired, and has a fresh JTI.
    - Caller is responsible for the outer transaction; this function uses a savepoint
      so that a concurrent rotate on the same JTI does not corrupt the outer txn.
    """
    from ..db import get_db  # avoid circular import at module level
    # Use the already-injected session; if none passed, get a fresh one.
    if not isinstance(db, Session):
        from .db import get_db as _get_db
        db = _get_db()

    # Generate JTI if not provided
    if jti is None:
        jti = f"{TEST_JTI_PREFIX}{user_id}:{int(time.time() * 1000)}"

    # The actual refresh-token value (opaque random) is generated by the caller
    # and its hash is passed in; here we create the DB row.  The token value
    # itself is never stored — only its hash so we can compare on validation.
    # In practice the caller (login / refresh endpoint) holds the plain token
    # temporarily and computes the hash for storage/comparison.
    from hashlib import sha256
    import secrets

    # Generate a cryptographically random token value; the hash is what we store.
    token_value = secrets.token_urlsafe(64)
    token_hash = sha256(token_value.encode()).hexdigest()[:128]

    expires_at = datetime.now(timezone.utc) + timedelta(
        minutes=settings.REFRESH_TOKEN_EXPIRE_MINUTES  # type: ignore[attr-defined]
    )

    rt = RefreshToken(
        user_id=user_id,
        token_hash=token_hash,
        jti=jti,
        expires_at=expires_at,
        ip_address=ip_address,
        user_agent=user_agent,
    )
    db.add(rt)
    try:
        db.flush()
    except SQLAlchemyError:
        db.rollback()
        raise
    return rt


def validate_refresh_token(jti: str, token_hash: str, db: Session) -> RefreshToken:
    """Validate a refresh token by JTI and stored hash.

    - Returns the RefreshToken row if valid (not revoked, not expired).
    - Raises 401 if the token is not found, revoked, or expired.
    - This function is idempotent: repeated calls with the same valid JTI
      always return the same row (no side effects).
    """
    from ..models import RefreshToken

    rt = db.query(RefreshToken).filter(RefreshToken.jti == jti).first()
    if rt is None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Invalid refresh token"
        )
    if rt.revoked_at is not None:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Refresh token revoked"
        )
    if rt.expires_at is not None and rt.expires_at < datetime.now(timezone.utc):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Refresh token expired"
        )
    # Reuse-prevention: compare stored hash with the presented hash.
    # The plain token value is not stored; the caller must present the hash
    # that was originally recorded.  If the hash doesn't match, the token
    # belongs to a different family and must be rejected.
    if rt.token_hash != token_hash:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED, detail="Refresh token reuse detected"
        )
    return rt


def rotate_refresh_token(
    jti: str,
    token_hash: str,
    ip_address: str | None = None,
    user_agent: str | None = None,
    db: Session | None = None,
) -> tuple[RefreshToken, RefreshToken]:
    """Rotate a refresh token: invalidate the old one and issue a new one.

    Returns (old_token, new_token).

    Concurrency safety: we use a savepoint on the old-token row.  If another
    request simultaneously rotates the same JTI, the first to flush wins;
    the second gets an IntegrityError / savepoint rollback and must re-read
    the current state and retry.

    Raises 401 if the token is invalid, revoked, or expired.
    """
    from ..models import RefreshToken
    import time as _time

    if db is None:
        from .db import get_db as _get_db
        db = _get_db()

    # First validate the existing token (checks existence, revocation, expiry, hash)
    old_rt = validate_refresh_token(jti, token_hash, db)

    # If we get here the token is valid.  Now use a savepoint so that a
    # concurrent rotate on the same JTI cannot corrupt us.
    sp = db.begin_nested()

    # Revoke the old token atomically within the savepoint
    old_rt.revoked_at = datetime.now(timezone.utc)

    # Create the new refresh token for the same user
    new_rt = create_refresh_token(db, user_id=old_rt.user_id, jti=jti, ip_address=ip_address, user_agent=user_agent)

    try:
        db.flush()
    except SQLAlchemyError:
        sp.rollback()
        raise

    sp.commit()
    return old_rt, new_rt


def revoke_refresh_token(jti: str, token_hash: str, db: Session) -> None:
    """Revoke a refresh token by JTI and hash.  Idempotent: if the token
    is already revoked or expired, no error is raised — the function simply
    ensures the row is marked revoked or the expiry is set.
    """
    from ..models import RefreshToken

    rt = db.get(RefreshToken, jti)
    if rt is None:
        # Already gone; nothing to do.
        return
    if rt.revoked_at is not None:
        # Already revoked; idempotent.
        return
    rt.revoked_at = datetime.now(timezone.utc)


def get_valid_refresh_token(jti: str, db: Session) -> RefreshToken | None:
    """Look up a refresh token by JTI and return it if it is valid (not revoked,
    not expired).  Returns None if the JTI is not found or the token is
    revoked/expired.  Idempotent — no side effects."""
    from ..models import RefreshToken

    rt = db.get(RefreshToken, jti)
    if rt is None:
        return None
    if rt.revoked_at is not None:
        return None
    if rt.expires_at is not None and rt.expires_at < datetime.now(timezone.utc):
        return None
    return rt